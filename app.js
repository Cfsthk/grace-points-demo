function exportReport() {
  const header = ["Academic Year", "Teacher", "Email", "Gross Awarded", "Remaining Allowance", "Students Rewarded"];
  const rows = teachers.map((teacher) => [state.currentYear, `${teacher.nameZh} ${teacher.nameEn}`, teacher.email, teacher.spent, teacher.balance, teacher.students]);
  const csv = `\uFEFF${[header, ...rows].map((row) => row.map((cell) => `"${String(cell).replaceAll('"', '""')}"`).join(",")).join("\n")}`;
  const blob = new Blob([csv], { type: "text/csv;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = `grace-points-${state.currentYear}.csv`;
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
  showToast(t("downloadSuccess"));
}

function openModal(html, onReady) {
  modalRoot.innerHTML = `<div class="modal-backdrop" role="presentation"><section class="modal" role="dialog" aria-modal="true">${html}</section></div>`;
  modalRoot.querySelectorAll("[data-modal-close]").forEach((button) => button.addEventListener("click", closeModal));
  modalRoot.querySelector(".modal-backdrop").addEventListener("click", (event) => {
    if (event.target.classList.contains("modal-backdrop")) closeModal();
  });
  document.addEventListener("keydown", handleModalEscape);
  if (onReady) onReady();
}

function handleModalEscape(event) {
  if (event.key === "Escape") closeModal();
}

function closeModal() {
  modalRoot.innerHTML = "";
  document.removeEventListener("keydown", handleModalEscape);
}

function openAdminPin() {
  openModal(`
    <span class="modal-kicker">${t("adminPortal")}</span>
    <h2>${t("adminPinTitle")}</h2>
    <p>${t("adminPinDesc")}</p>
    <div class="field-group pin-field">
      <label for="admin-pin">${t("pinLabel")}</label>
      <input id="admin-pin" type="password" inputmode="numeric" pattern="[0-9]*" maxlength="4" autocomplete="off" placeholder="••••" />
    </div>
    <p class="pin-hint">${t("pinHint")}</p>
    <p class="login-error" id="pin-error"></p>
    <div class="modal-actions">
      <button class="secondary-button" type="button" data-modal-close>${t("cancel")}</button>
      <button class="primary-button" type="button" id="unlock-admin">${t("unlockAdmin")}</button>
    </div>
  `, () => {
    const input = modalRoot.querySelector("#admin-pin");
    const submit = () => {
      const pin = input.value.replace(/\D/g, "").slice(0, 4);
      input.value = pin;
      if (pin !== "2026") {
        modalRoot.querySelector("#pin-error").textContent = t("incorrectPin");
        input.focus();
        input.select();
        return;
      }
      state.role = "admin";
      closeModal();
      renderApp();
      window.scrollTo({ top: 0, behavior: "auto" });
    };
    input.addEventListener("input", () => {
      input.value = input.value.replace(/\D/g, "").slice(0, 4);
      modalRoot.querySelector("#pin-error").textContent = "";
    });
    input.addEventListener("keydown", (event) => {
      if (event.key === "Enter") submit();
    });
    modalRoot.querySelector("#unlock-admin").addEventListener("click", submit);
    input.focus();
  });
}

