function bindTeacherEvents() {
  main.querySelectorAll("[data-teacher-tab]").forEach((button) => {
    button.addEventListener("click", () => {
      state.teacherTab = button.dataset.teacherTab;
      renderTeacher();
    });
  });

  main.querySelectorAll("[data-roster-mode]").forEach((button) => {
    button.addEventListener("click", () => {
      state.rosterMode = button.dataset.rosterMode;
      state.selected.clear();
      state.search = "";
      renderTeacher();
    });
  });

  const gradeFilter = main.querySelector("#grade-filter");
  if (gradeFilter) gradeFilter.addEventListener("change", (event) => {
    state.grade = event.target.value === "all" ? "all" : Number(event.target.value);
    state.selected.clear();
    renderTeacher();
  });

  const classFilter = main.querySelector("#class-filter");
  if (classFilter) classFilter.addEventListener("change", (event) => {
    state.homeClass = event.target.value;
    state.selected.clear();
    renderTeacher();
  });

  const subjectFilter = main.querySelector("#subject-filter");
  if (subjectFilter) subjectFilter.addEventListener("change", (event) => {
    state.subject = event.target.value;
    state.selected.clear();
    renderTeacher();
  });

  const groupFilter = main.querySelector("#group-filter");
  if (groupFilter) groupFilter.addEventListener("change", (event) => {
    state.group = event.target.value;
    state.selected.clear();
    renderTeacher();
  });

  main.querySelectorAll("[data-recent]").forEach((button) => {
    button.addEventListener("click", () => {
      const preset = button.dataset.recent;
      state.rosterMode = "subject";
      if (preset === "p5-blue") Object.assign(state, { grade: 5, subject: "English", group: "Blue" });
      if (preset === "p4-red") Object.assign(state, { grade: 4, subject: "Chinese", group: "Red" });
      if (preset === "p6-green") Object.assign(state, { grade: 6, subject: "Mathematics", group: "Green" });
      state.selected.clear();
      state.search = "";
      renderTeacher();
    });
  });

  main.querySelectorAll("[data-select-student]").forEach((button) => {
    button.addEventListener("click", () => {
      const id = button.dataset.selectStudent;
      state.selected.has(id) ? state.selected.delete(id) : state.selected.add(id);
      renderTeacher();
    });
  });

  const selectAllButton = main.querySelector("[data-select-all]");
  if (selectAllButton) selectAllButton.addEventListener("click", () => {
    const roster = filteredStudents();
    const shouldSelect = !roster.every((student) => state.selected.has(student.id));
    roster.forEach((student) => shouldSelect ? state.selected.add(student.id) : state.selected.delete(student.id));
    renderTeacher();
  });

  const search = main.querySelector("#student-search");
  if (search) search.addEventListener("input", (event) => {
    state.search = event.target.value;
    const needle = state.search.trim().toLowerCase();
    main.querySelectorAll("[data-student-row]").forEach((row) => {
      row.hidden = needle && !row.dataset.search.includes(needle);
    });
    const count = main.querySelector("#roster-count");
    if (count) count.textContent = `${filteredStudents().length} ${t("students")}`;
  });

  main.querySelectorAll("[data-points]").forEach((button) => {
    button.addEventListener("click", () => {
      state.points = Number(button.dataset.points);
      renderTeacher();
    });
  });

  const customPoints = main.querySelector("#custom-points");
  if (customPoints) customPoints.addEventListener("input", (event) => {
    state.points = Math.max(1, Math.round(Number(event.target.value) || 1));
    main.querySelectorAll("[data-points]").forEach((button) => button.classList.remove("active"));

    const count = filteredStudents().filter((student) => state.selected.has(student.id)).length;
    const total = count * state.points;
    const resultingBalance = currentTeacher().balance - total;
    const summaryRows = main.querySelectorAll(".award-summary .summary-row");
    if (summaryRows.length === 2) {
      summaryRows[0].querySelector("strong").textContent = formatNumber(total);
      summaryRows[1].querySelector("strong").textContent = formatNumber(resultingBalance);
      summaryRows[1].classList.toggle("negative", resultingBalance < 0);
    }

    const rewardPanel = main.querySelector(".reward-compose");
    const existingWarning = rewardPanel?.querySelector(".balance-warning");
    if (resultingBalance < 0 && count > 0 && !existingWarning) {
      const warning = document.createElement("div");
      warning.className = "balance-warning compose-warning";
      warning.textContent = t("lowWarning");
      rewardPanel.querySelector("#award-button").before(warning);
    } else if ((resultingBalance >= 0 || count === 0) && existingWarning) {
      existingWarning.remove();
    }
  });

  const mobilePoints = main.querySelector("#mobile-points");
  if (mobilePoints) mobilePoints.addEventListener("input", (event) => {
    state.points = Math.max(1, Math.round(Number(event.target.value) || 1));
    const count = filteredStudents().filter((student) => state.selected.has(student.id)).length;
    const awardButton = main.querySelector("#award-button");
    if (awardButton) awardButton.innerHTML = `${t("givePoints")}${count ? ` · ${count} × ${state.points}` : ""} <span aria-hidden="true">→</span>`;
  });

  const reason = main.querySelector("#reward-reason");
  if (reason) reason.addEventListener("input", (event) => {
    state.reason = event.target.value;
  });

  const awardButton = main.querySelector("#award-button");
  if (awardButton) awardButton.addEventListener("click", openAwardConfirmation);

  main.querySelectorAll("[data-view-student]").forEach((button) => {
    button.addEventListener("click", () => openStudentPreview(button.dataset.viewStudent));
  });

  main.querySelectorAll("[data-reverse-activity]").forEach((button) => {
    button.addEventListener("click", () => openReverseConfirmation(button.dataset.reverseActivity));
  });
}

function openAwardConfirmation() {
  const selected = filteredStudents().filter((student) => state.selected.has(student.id));
  if (!selected.length) return;
  const total = selected.length * state.points;
  openModal(`
    <span class="modal-kicker">Grace Points · 恩之果積分</span>
    <h2>${t("rewardConfirm")}</h2>
    <p>${t("rewardConfirmText", { points: state.points, count: selected.length })}</p>
    <div class="modal-summary">
      <div class="summary-row"><span>${t("name")}</span><strong>${selected.slice(0, 3).map((student) => student.nameZh).join("、")}${selected.length > 3 ? ` +${selected.length - 3}` : ""}</strong></div>
      <div class="summary-row"><span>${t("reason")}</span><strong>${escapeHtml(state.reason || "—")}</strong></div>
      <div class="summary-row"><span>${t("totalCost")}</span><strong>${formatNumber(total)}</strong></div>
    </div>
    <div class="modal-actions">
      <button class="secondary-button" type="button" data-modal-close>${t("cancel")}</button>
      <button class="primary-button" type="button" id="confirm-award">${t("confirmAward")}</button>
    </div>
  `, () => {
    modalRoot.querySelector("#confirm-award").addEventListener("click", () => {
      const batch = `B-${Date.now().toString().slice(-4)}`;
      selected.forEach((student) => {
        student.balance += state.points;
        activities.unshift({
          id: `a-${Date.now()}-${student.id}`,
          batch,
          studentId: student.id,
          type: "award",
          amount: state.points,
          reason: state.reason,
          date: "Today, now",
          status: "active",
        });
        if (!studentHistories[student.id]) studentHistories[student.id] = [];
        studentHistories[student.id].unshift({
          type: "award",
          amount: state.points,
          reasonEn: state.reason || "Grace Points award",
          reasonZh: state.reason || "恩之果積分獎勵",
          teacherEn: currentTeacher().nameEn,
          teacherZh: currentTeacher().nameZh,
          date: "Today",
        });
      });
      currentTeacher().balance -= total;
      currentTeacher().spent += total;
      closeModal();
      state.selected.clear();
      state.reason = "";
      renderTeacher();
      showToast(t("rewardSuccess", { count: selected.length }));
    });
  });
}

