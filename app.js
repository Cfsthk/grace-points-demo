function openReverseConfirmation(activityId) {
  const item = activities.find((activity) => activity.id === activityId);
  const student = getStudent(item.studentId);
  const blocked = item.type === "award" && student.balance < item.amount;
  if (blocked) {
    showToast(t("reverseBlocked"));
    return;
  }
  openModal(`
    <span class="modal-kicker">${item.batch}</span>
    <h2>${t("reverseConfirm")}</h2>
    <p>${item.type === "award" ? t("reverseText") : `${t("redeemed")} · ${student.nameZh}`}</p>
    <div class="modal-summary">
      <div class="summary-row"><span>${t("name")}</span><strong>${student.nameZh} · ${student.nameEn}</strong></div>
      <div class="summary-row"><span>${t("amount")}</span><strong>${item.amount}</strong></div>
    </div>
    <div class="modal-actions">
      <button class="secondary-button" type="button" data-modal-close>${t("cancel")}</button>
      <button class="danger-button" type="button" id="confirm-reverse">${t("confirmReverse")}</button>
    </div>
  `, () => {
    modalRoot.querySelector("#confirm-reverse").addEventListener("click", () => {
      if (item.type === "award") {
        student.balance -= item.amount;
        currentTeacher().balance += item.amount;
        currentTeacher().spent -= item.amount;
      } else {
        student.balance += item.amount;
      }
      item.status = "reversed";
      closeModal();
      renderTeacher();
      showToast(t("reverseSuccess"));
    });
  });
}

